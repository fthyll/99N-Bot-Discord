"""Build the event-icon pack: download coc.guide art, convert, manifest.

The pack is committed (assets/events/*.webp), so this runs only when the icon
set changes. Idempotent: same names -> same filenames -> no git churn.

Source rules (see the game-item-icon-packs skill):
- image paths derive from the game's data key, not the display name
- HEAD-validate every URL before downloading
"""

import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "events"
MANIFEST = ROOT / "bot" / "event_icons.py"

# group -> (source path on coc.guide, why this art represents the group)
SOURCES = {
    "war": ("hero/barbarian-king.png", "Barbarian King — war face"),
    "raid": ("troop/goblin.png", "Goblin — raid weekend face"),
    "clan": ("hero/archer-queen.png", "Archer Queen — clan face"),
    "system": ("spell/lighningstorm.png", "Lightning spell — system alert face"),
}


def head_ok(url):
    req = Request(url, method="HEAD", headers={"User-Agent": "99N-bot-pack-builder"})
    with urlopen(req, timeout=30) as resp:
        return resp.status == 200 and int(resp.headers.get("Content-Length") or 0) > 0


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for group, (src, why) in SOURCES.items():
        url = f"https://coc.guide/static/imgs/{src}"
        if not head_ok(url):
            print(f"FAIL {group}: {url} did not HEAD-validate")
            sys.exit(1)
        stem = Path(src).stem
        with tempfile.TemporaryDirectory() as d:
            tmp = Path(d) / f"{stem}.png"
            req = Request(url, headers={"User-Agent": "99N-bot-pack-builder"})
            tmp.write_bytes(urlopen(req, timeout=60).read())
            dest = OUT / f"{group}.webp"
            subprocess.run(
                ["magick", str(tmp), "-resize", "160x160", str(dest)], check=True
            )
        print(f"ok {group} <- {src} ({why})")

    # Regenerate the manifest from the same run so files and manifest cannot
    # drift apart.
    lines = [
        '"""Manifest mapping notification groups to local icon files.',
        "",
        "Icons come from coc.guide (game-file artwork, ad-free) and are committed as",
        "WebP in assets/events/ — the embeds attach them, never hotlink. Generated by",
        "scripts/fetch_event_icons.py; edit the SOURCES table there, not this file.",
        '"""',
        "",
        "from pathlib import Path",
        "",
        "EVENT_ICONS = {",
    ]
    for group in SOURCES:
        lines.append(f'    "{group}": "events/{group}.webp",')
    lines += [
        "}",
        "",
        "",
        "def icon_path(group):",
        '    """Absolute path for a group\'s icon, or None when the pack lacks it."""',
        "    rel = EVENT_ICONS.get(group)",
        "    if not rel:",
        "        return None",
        '    path = Path(__file__).resolve().parent.parent / "assets" / rel',
        "    return path if path.exists() else None",
        "",
    ]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
