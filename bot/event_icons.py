"""Manifest mapping notification groups to local icon files.

Icons come from coc.guide (game-file artwork, ad-free) and are committed as
WebP in assets/events/ — the embeds attach them, never hotlink. Generated by
scripts/fetch_event_icons.py; edit the SOURCES table there, not this file.
"""

from pathlib import Path

EVENT_ICONS = {
    "war": "events/war.webp",
    "raid": "events/raid.webp",
    "clan": "events/clan.webp",
    "system": "events/system.webp",
}


def icon_path(group):
    """Absolute path for a group's icon, or None when the pack lacks it."""
    rel = EVENT_ICONS.get(group)
    if not rel:
        return None
    # The pack lives beside the repo root (ASSET_DIR), not inside bot/.
    path = Path(__file__).resolve().parent.parent / "assets" / rel
    return path if path.exists() else None
